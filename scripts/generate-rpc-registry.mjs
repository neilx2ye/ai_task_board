#!/usr/bin/env node
/* global process */
/**
 * Regenerate lib/db/rpc-registry.generated.ts from a live database that has
 * supabase/migrations/ applied. Run after adding or changing RPC signatures:
 *
 *   DATABASE_URL=postgresql:///ai_task_board_local node scripts/generate-rpc-registry.mjs
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { Client } from "pg";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputFile = path.join(projectRoot, "lib", "db", "rpc-registry.generated.ts");
const connectionString =
  process.env.DATABASE_URL ?? "postgresql:///ai_task_board_local";

const client = new Client({ connectionString });
await client.connect();
try {
  const { rows } = await client.query(`
    select p.proname as name,
           p.proargnames as argnames,
           (select array_agg(format_type(t.t, null))
            from unnest(p.proargtypes) as t(t)) as argtypes,
           format_type(p.prorettype, null) as rettype,
           p.pronargdefaults as defaults
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public'
      and p.prokind = 'f'
      and p.proargnames is not null
    order by p.proname
  `);

  const registry = new Map();
  for (const row of rows) {
    const names = row.argnames ?? [];
    const types = row.argtypes ?? [];
    const args = names.map((name, index) => ({
      name,
      type: types[index] ?? "text",
    }));
    const signatures = registry.get(row.name) ?? [];
    signatures.push({
      args,
      returns: row.rettype,
      defaults: Number(row.defaults ?? 0),
    });
    registry.set(row.name, signatures);
  }

  const entries = [...registry.entries()]
    .map(([name, signatures]) => {
      const body = JSON.stringify(signatures, null, 2)
        .split("\n")
        .map((line, index) => (index === 0 ? line : `  ${line}`))
        .join("\n");
      return `  ${JSON.stringify(name)}: ${body},`;
    })
    .join("\n");

  const source = `// Generated by scripts/generate-rpc-registry.mjs. Do not edit by hand.
export type RpcArg = {
  name: string;
  type: string;
};

export type RpcSignature = {
  args: RpcArg[];
  returns: string;
  defaults: number;
};

export const RPC_REGISTRY: Record<string, RpcSignature[]> = {
${entries}
};
`;
  writeFileSync(outputFile, source);
  console.log(`wrote ${outputFile} (${registry.size} functions)`);
} finally {
  await client.end();
}
